function lifeMapCoordinate(region: string, index: number) {
  const center = lifeMapRegionCenters[region] || { lat: 36.713, lng: 127.429 }
  const latOffset = ((((index * 7) % 11) - 5) * 0.006)
  const lngOffset = ((((index * 5) % 13) - 6) * 0.007)
  return {
    lat: Number((center.lat + latOffset).toFixed(6)),
    lng: Number((center.lng + lngOffset).toFixed(6)),
  }
}

