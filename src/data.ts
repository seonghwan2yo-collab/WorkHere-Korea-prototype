function enrichPlaceReviews(place: Place, index: number) {
  const templates = placeReviewTemplates(place)
  const reviews = [...place.reviews, ...templates]
    .filter((review, reviewIndex, list) => list.indexOf(review) === reviewIndex)
    .slice(0, 4)
  return {
    ...place,
    reviews: reviews.length >= 3
      ? reviews
      : [...reviews, `최근 ${place.region} 이용자들이 확인한 생활도움 장소입니다.`].slice(0, 3 + (index % 2)),
  }
}

